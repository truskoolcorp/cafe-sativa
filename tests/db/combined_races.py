"""LOCAL disposable combined-candidate races; imported only after harness opt-in.

No schema/ACL changes, identity overrides, role escalation or direct ledger deletes.
All INSERT contenders use the existing service old-column permission surface.
"""
import concurrent.futures
import json
import os
from pathlib import Path
import re
import selectors
import subprocess
import time
import uuid


def assert_sqlstate(result, expected):
    errors = re.findall(r'^ERROR:\s+([0-9A-Z]{5}): [^\r\n]+$', result.get('error', ''), re.MULTILINE)
    assert errors == [expected], result


def terminal_insert(db, ids, *, old=False):
    """Ordinary old-column INSERT. Numeric identity is generated by PostgreSQL."""
    age = "clock_timestamp()-interval '4 days'" if old else 'clock_timestamp()'
    finish = "clock_timestamp()-interval '3 days'" if old else 'clock_timestamp()'
    values = [f"({db.literal('s:combined-direct-'+rid)},{db.literal(rid)}::uuid,true,'cancelled',false,{age},{age}+interval '60 seconds',{finish},1,NULL,NULL,NULL)" for rid in ids]
    return ('INSERT INTO concierge_private.requests(requester,request_id,redacted,state,charged,'
            'admitted_at,lease_until,finished_at,reserved_cost_microusd,owner_token,user_message_id,assistant_message_id) VALUES '
            + ','.join(values) + ';')


def admission_sql(db, session, rid):
    return f"SELECT public.concierge_admit_v1(NULL,{db.literal(session)},{db.literal(rid)}::uuid,{db.literal(db.payload(rid))}::jsonb,'anonymous');"


def hold_then(db, statement, calls, *, role='service_role', rollback=False, timeout=False):
    """Hold a real entrypoint, prove each waiter belongs to its backend, release.

    The holder takes no artificial advisory lock. Startup reads and the entire
    interactive session are bounded even if psql fails before its ready marker.
    """
    proc = subprocess.Popen(['psql', '-X', '-qAt', '-v', 'ON_ERROR_STOP=1', '-v', 'VERBOSITY=verbose'],
                            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    lines = []
    try:
        role_sql = f'SET LOCAL ROLE {role};' if role else ''
        proc.stdin.write(("BEGIN; SET LOCAL statement_timeout='8s'; SET LOCAL idle_in_transaction_session_timeout='8s'; "
                          + role_sql + statement + " SELECT 'holder:'||pg_backend_pid();\n").encode())
        proc.stdin.flush()
        deadline, pending, pid = time.monotonic()+8, b'', None
        with selectors.DefaultSelector() as selector:
            selector.register(proc.stdout, selectors.EVENT_READ)
            while pid is None:
                remaining = deadline-time.monotonic()
                if remaining <= 0 or not selector.select(remaining):
                    raise AssertionError('holder startup timed out')
                chunk = os.read(proc.stdout.fileno(), 65536)
                if not chunk:
                    raise AssertionError('holder failed before marker: '+proc.stderr.read().decode())
                pending += chunk
                while b'\n' in pending:
                    line, pending = pending.split(b'\n', 1)
                    line = line.decode().strip()
                    if line.startswith('holder:'):
                        pid = int(line.split(':')[1])
                    elif line:
                        lines.append(line)
        with concurrent.futures.ThreadPoolExecutor(max_workers=len(calls)) as pool:
            futures = [pool.submit(call) for call in calls]
            deadline = time.monotonic()+1.4
            try:
                while time.monotonic()<deadline:
                    # pg_blocking_pids includes soft queue blockers, so follow
                    # the holder's advisory lock tag as well as this database.
                    waiting = int(db.sql(f"SELECT count(DISTINCT w.pid) FROM pg_locks w JOIN pg_locks h ON h.locktype=w.locktype AND h.database=w.database AND h.classid=w.classid AND h.objid=w.objid AND h.objsubid=w.objsubid WHERE h.pid={pid} AND h.granted AND w.locktype='advisory' AND w.classid=1128351301 AND w.objid=1 AND NOT w.granted;"))
                    if waiting == len(calls):
                        break
                    time.sleep(.01)
                else:
                    raise AssertionError('every contender must reach the actual holder advisory-lock wait')
                if timeout:
                    results = [future.result(timeout=6) for future in futures]
                else:
                    results = None
            finally:
                proc.stdin.write(b'ROLLBACK;\n' if rollback else b'COMMIT;\n')
                proc.stdin.close()
                proc.wait(timeout=8)
            assert proc.returncode == 0, proc.stderr.read().decode()
            return lines, results if results is not None else [future.result(timeout=8) for future in futures]
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait(timeout=3)
        for pipe in (proc.stdin, proc.stdout, proc.stderr):
            if pipe and not pipe.closed:
                pipe.close()



# Hash inside PostgreSQL: only digests, never retained payload/response content,
# leave the disposable database. Stable identity ordering includes every row.
MAINTENANCE_FINGERPRINT = """SELECT jsonb_build_object(
 'lifecycle', (SELECT md5(row_to_json(l)::text) FROM concierge_private.lifecycle l WHERE singleton),
 'ledger', (SELECT md5(coalesce(string_agg(md5(row_to_json(r)::text),'' ORDER BY cleanup_scan_id),'')) FROM concierge_private.requests r)
)::text;"""


def checked_command_with_timeout(command):
    marker = 'END $cleanup_job$;'
    assert command.count(marker) == 1, 'checked cleanup command terminator changed'
    return command.replace(marker, 'PERFORM pg_catalog.pg_sleep(6);\n'+marker, 1)


def maintenance_timeout_recovery(db):
    command = Path(__file__).with_name('cleanup_checked_command.sql').read_text()
    before = db.sql(MAINTENANCE_FINGERPRINT)
    result = db.captured(lambda: db.sql(checked_command_with_timeout(command)))
    assert_sqlstate(result, '57014')
    assert db.sql(MAINTENANCE_FINGERPRINT) == before, 'timed-out maintenance changed lifecycle or ledger fingerprint'
    # Same checked command, unchanged policy and ordinary object-owner session.
    # Its built-in assertions require a fresh successful maintenance heartbeat.
    db.sql(command)
    assert db.sql(MAINTENANCE_FINGERPRINT) != before, 'successful maintenance did not advance lifecycle fingerprint'
    print('PASS checked maintenance outer statement timeout rolls back ledger/cursor/heartbeat; ordinary retry succeeds')


def run(db):
    def count():
        return int(db.sql('SELECT count(*) FROM concierge_private.requests;'))

    def direct(ids, **kwargs):
        return db.captured(lambda: db.as_role(terminal_insert(db, ids, **kwargs), 'service_role'))

    def admit(session, rid=None):
        rid = rid or db.request_id()
        return json.loads(db.as_role(admission_sql(db, session, rid), 'service_role'))

    def maintain(limit=1000):
        result = json.loads(db.sql(f'SELECT concierge_private.maintain_v1({limit});'))
        assert 0 <= result['inspected'] <= limit and isinstance(result['sweep_completed'], bool), result
        return result

    db.configure()
    base=count(); db.configure(max_retained_requests=base+1)
    results=db.race([lambda i=i: admit(f'combined-rpc-{i}') for i in range(4)])
    winners=[r for r in results if r.get('admitted') is True]
    assert len(winners)==1 and sum(r.get('error')=='capacity_busy' for r in results)==3, results
    assert count()==base+1
    db.finish(winners[0])
    print('PASS combined retained ceiling: RPC/RPC last slot')

    base=count(); db.configure(max_retained_requests=base+1)
    rid=db.request_id()
    results=db.race([lambda: admit('combined-rpc-direct'), lambda: direct([rid])])
    if results[0].get('admitted') is True:
        assert_sqlstate(results[1], 'PCB02'); db.finish(results[0])
    else:
        assert results[0].get('error')=='capacity_busy' and 'ok' in results[1],results
    assert count()==base+1
    print('PASS combined retained ceiling: RPC/direct service INSERT last slot')

    # Two two-row statements compete for three slots: no partial loser rows.
    base=count(); db.configure(max_retained_requests=base+3)
    groups=[[db.request_id(),db.request_id()] for _ in range(2)]
    results=db.race([lambda ids=ids: direct(ids) for ids in groups])
    assert sum('ok' in r for r in results)==1,results
    for ids,result in zip(groups,results):
        if 'error' in result: assert_sqlstate(result,'PCB02')
        present=int(db.sql('SELECT count(*) FROM concierge_private.requests WHERE request_id IN ('+','.join(db.literal(x)+'::uuid' for x in ids)+');'))
        assert present==(2 if 'ok' in result else 0),(result,present)
    assert count()==base+2
    print('PASS combined multi-row contenders: losing statement rolls back every row')

    # Saturation cannot obstruct existing status, replay, recovery or completion.
    db.configure(); a=admit('combined-complete'); expired=admit('combined-recover')
    db.configure(max_retained_requests=count())
    rid=a['request_id']
    status=json.loads(db.as_role(f"SELECT public.concierge_status_v1(NULL,'combined-complete',{db.literal(rid)}::uuid,{db.literal(db.payload(rid))}::jsonb);",'service_role'))
    assert status.get('state')=='reserved',status
    replay=admit('combined-complete',rid)
    assert replay.get('admitted') is False and 'owner_token' not in replay,replay
    complete=json.loads(db.as_role(f"SELECT public.concierge_complete_v1({db.literal(a['requester'])},{db.literal(rid)}::uuid,{db.literal(a['owner_token'])}::uuid,'hello','combined local reply',false);",'service_role'))
    assert complete.get('state')=='completed',complete
    db.sql(f"UPDATE concierge_private.requests SET admitted_at=clock_timestamp()-interval '2 minutes',lease_until=clock_timestamp()-interval '1 minute' WHERE request_id={db.literal(expired['request_id'])}::uuid;")
    recovered=admit('combined-recover',expired['request_id'])
    assert recovered.get('state')=='cancelled',recovered
    assert admit('combined-still-full').get('error')=='capacity_busy'
    print('PASS combined saturation preserves status/replay/completion and expired-reservation recovery')

    # Rollback releases the last slot. A successful holder INSERT must not leak
    # its row; a queued real service INSERT then wins without policy expansion.
    base=count(); db.configure(max_retained_requests=base+1)
    holder,contender=db.request_id(),db.request_id()
    _,results=hold_then(db,terminal_insert(db,[holder]),[lambda: direct([contender])],rollback=True)
    assert 'ok' in results[0] and count()==base+1,results
    assert db.sql(f'SELECT count(*) FROM concierge_private.requests WHERE request_id={db.literal(holder)}::uuid;')=='0'
    base=count(); db.configure(max_retained_requests=base+1)
    holder,contender=db.request_id(),db.request_id()
    _,results=hold_then(db,terminal_insert(db,[holder]),[lambda: direct([contender])],rollback=True,timeout=True)
    assert_sqlstate(results[0],'55P03')
    assert count()==base
    assert 'ok' in direct([contender])
    print('PASS combined rollback holder and observed real INSERT lock timeout leave no partial charge/row')

    # Start a new finite sweep with a known eligible tail, then append beyond its
    # boundary. Existing rows are never deleted by fixture SQL.
    db.configure()
    for _ in range(count()+2):
        if maintain()['sweep_completed']: break
    else: raise AssertionError('could not finish prior sweep')
    old=str(uuid.UUID(int=((int(time.time()*1000)-4*86400000)<<80)|(uuid.UUID(db.request_id()).int&((1<<80)-1))))
    assert 'ok' in direct([old],old=True)
    bound=int(db.sql('SELECT max(cleanup_scan_id) FROM concierge_private.requests;'))
    db.configure(max_retained_requests=count()+1)
    appended=db.request_id()
    lines,results=hold_then(db,'SELECT concierge_private.maintain_v1(1);',[
        lambda: direct([appended]),lambda: admit('combined-direct-'+old,old)],role=None)
    first=json.loads(lines[0]); assert first['inspected']==1 and first['sweep_completed'] is False,first
    assert 'ok' in results[0] and results[1].get('error') in ('gone','request_expired'),results
    assert int(db.sql('SELECT cleanup_scan_through FROM concierge_private.lifecycle;'))==bound
    appended_scan=int(db.sql(f'SELECT cleanup_scan_id FROM concierge_private.requests WHERE request_id={db.literal(appended)}::uuid;'))
    assert appended_scan>bound
    previous=int(db.sql('SELECT cleanup_scan_after FROM concierge_private.lifecycle;'))
    for _ in range(count()+2):
        # Every batch races a same-ID replay through the installed entrypoints.
        results=db.race([lambda: maintain(1),lambda: admit('combined-direct-'+old,old)])
        batch=results[0]; assert results[1].get('error') in ('gone','request_expired'),results
        if batch['sweep_completed']:
            break
        cursor=int(db.sql('SELECT cleanup_scan_after FROM concierge_private.lifecycle;'))
        assert previous<cursor<=bound,(previous,cursor,bound)
        previous=cursor
    else: raise AssertionError('finite sweep did not wrap within original retained-row bound')
    assert db.sql(f'SELECT count(*) FROM concierge_private.requests WHERE request_id={db.literal(old)}::uuid;')=='0'
    assert db.sql(f'SELECT count(*) FROM concierge_private.requests WHERE request_id={db.literal(appended)}::uuid;')=='1'
    assert admit('combined-direct-'+old,old).get('error')=='request_expired'
    assert db.sql('SELECT cleanup_scan_after=0 AND cleanup_scan_through IS NULL FROM concierge_private.lifecycle;')=='t'
    recovered=admit('combined-after-prune')
    assert recovered.get('admitted') is True,recovered
    db.finish(recovered)
    db.configure()
    # Reverse ordering: a real INSERT holder makes maintenance wait. Its commit
    # belongs to the next sweep, and bounded progress still reaches completion.
    new=db.request_id()
    _,results=hold_then(db,terminal_insert(db,[new]),[lambda: maintain(1)])
    assert results[0]['inspected']==1,results
    before=db.sql('SELECT row_to_json(lifecycle) FROM concierge_private.lifecycle;')
    _,results=hold_then(db,'SELECT concierge_private.maintain_v1(1);',
        [lambda: admit('combined-complete',a['request_id'])],role=None,rollback=True)
    assert results[0].get('state')=='completed',results
    assert db.sql('SELECT row_to_json(lifecycle) FROM concierge_private.lifecycle;')==before
    db.configure()
    print('PASS combined maintenance/append/replay: both lock orders, finite cursor wrap and eligible-tail pruning')
    maintenance_timeout_recovery(db)
