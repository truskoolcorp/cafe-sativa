const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const api = fs.readFileSync('app/api/events/[slug]/join/route.ts','utf8')
const watch = fs.readFileSync('app/events/[slug]/watch/page.tsx','utf8')
test('join secrets require signed-in identity and server-verified entitlement', () => {
 assert.match(api,/auth\.getUser\(\)/)
 assert.match(api,/from\('tickets'\)/)
 assert.match(api,/\.eq\('user_id', user\.id\)/)
 assert.match(api,/\['valid','used'\]/)
 assert.match(api,/member\.status === 'active'/)
 assert.match(api,/current_period_end/)
 assert.match(api,/return reply\(\{ error: 'Ticket or membership required\.' \}, 403\)/)
 assert.match(api,/private, no-store/)
})
test('watch does not query join credentials directly from database view', () => {
 assert.match(watch,/fetch\(`\/api\/events\//)
 assert.doesNotMatch(watch,/\.from\('tickets'\)/)
 assert.doesNotMatch(watch,/\.select\('[^']*zoom_join_url/)
})
