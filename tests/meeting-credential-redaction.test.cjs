const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const sql=fs.readFileSync('supabase/migrations/20261019_redact_event_join_credentials.sql','utf8')
test('public event reads cannot reach join or recording credentials',()=>{
 assert.match(sql,/REVOKE SELECT ON public\.events FROM PUBLIC, anon, authenticated/)
 assert.match(sql,/GRANT SELECT \(/)
 assert.match(sql,/NULL::text AS zoom_join_url/)
 assert.match(sql,/NULL::text AS zoom_meeting_id/)
 assert.match(sql,/has_column_privilege\('anon','public\.events','recording_url','SELECT'\)/)
 assert.match(sql,/m\.status='active'/)
 assert.match(sql,/current_period_end>now\(\)/)
 assert.match(sql,/COMMIT;/)
})
